import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.PREVIEW_URL ?? 'http://127.0.0.1:5173');
  await expect(page.getByRole('heading', { name: 'Patient board', exact: true })).toBeVisible();
  await expect(page.getByText('Alex Morgan', { exact: true })).toBeVisible();
  await page.locator('.table-scroll').evaluate(element => { element.scrollTop = element.scrollHeight; });
  const listBounds = await page.locator('.table-scroll').boundingBox();
  const headingBounds = await page.getByRole('columnheader', { name: 'Patient', exact: true }).boundingBox();
  if (!listBounds || !headingBounds || Math.abs(headingBounds.y - listBounds.y) > 2) throw new Error('Patient column headings do not stay frozen when scrolling.');
  await page.locator('.table-scroll').evaluate(element => { element.scrollTop = 0; });
  await page.getByRole('button', { name: 'Register patient', exact: true }).click();
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/patient-form-desktop.png' });
  const desktopFooter = await page.locator('.dialog-footer').boundingBox();
  if (!desktopFooter || desktopFooter.y + desktopFooter.height > 1000) throw new Error('Desktop save controls are outside the viewport.');
  await expect(page.getByLabel('Patient reference', { exact: true })).toHaveAttribute('readonly', '');
  await page.getByLabel('First name', { exact: true }).fill('Test');
  await page.getByLabel('Last name', { exact: true }).fill('Person');
  await page.getByLabel('Date of birth (optional if unknown)', { exact: true }).fill('1996-05-20');
  await page.getByLabel('Presenting complaint', { exact: true }).fill('Fictional test visit');
  await page.getByLabel('Assigned priority', { exact: true }).selectOption('2');
  await page.getByRole('dialog').getByRole('button', { name: 'Register patient', exact: true }).click();
  await expect(page.getByText('Patient registered.', { exact: true })).toBeVisible();
  await expect(page.getByText(/DEMO-PF-000001/)).toBeVisible();
  await page.getByRole('button', { name: 'View Test Person', exact: true }).click();
  await page.getByLabel('Assigned space', { exact: true }).selectOption('theatre-1');
  await page.getByLabel('Care status', { exact: true }).selectOption('in_treatment');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.reload();
  await expect(page.getByText('Test Person', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'View Test Person', exact: true }).click();
  await expect(page.getByLabel('Assigned space', { exact: true })).toHaveValue('theatre-1');
  await expect(page.getByLabel('Date of birth (optional if unknown)', { exact: true })).toHaveValue('1996-05-20');
  await page.getByLabel('Care status', { exact: true }).selectOption('discharged');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByText('Test Person', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Completed visits', exact: true }).click();
  await expect(page.getByText('Test Person', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Spaces & resources', exact: true }).click();
  await page.getByLabel('Status for Theatre 01').selectOption('cleaning');
  await expect(page.getByText('Space status updated.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Activity log', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Recent changes' })).toBeVisible();
  await page.getByRole('button', { name: /Patient board/ }).click();
  await page.getByRole('textbox', { name: 'Search patients' }).fill('Sam Taylor');
  await expect(page.getByText('Sam Taylor', { exact: true })).toBeVisible();
  await expect(page.getByText('Alex Morgan', { exact: true })).toHaveCount(0);
  await page.getByRole('textbox', { name: 'Search patients' }).fill('');
  await page.getByRole('combobox', { name: 'Filter by priority' }).selectOption('1');
  await expect(page.getByText('Sam Taylor', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Alex Morgan', { exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Filter by priority' }).selectOption('all');
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Display mode' }).click();
  await expect(page.getByText('Alex Morgan', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Register patient', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Exit display' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) {
    console.log(await page.evaluate(() => [...document.querySelectorAll('*')].filter(e => e.scrollWidth > e.clientWidth + 2).map(e => ({ tag: e.tagName, class: e.className, width: e.clientWidth, scroll: e.scrollWidth, overflow: getComputedStyle(e).overflowX }))));
    throw new Error('Mobile layout overflows the viewport.');
  }
  await page.getByRole('button', { name: 'Register patient', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.screenshot({ path: 'test-results/patient-form-mobile.png' });
  await page.locator('.dialog-body').evaluate(element => { element.scrollTop = element.scrollHeight; });
  const mobileFooter = await page.locator('.dialog-footer').boundingBox();
  const mobileHeading = await page.locator('.dialog-heading').boundingBox();
  if (!mobileFooter || mobileFooter.y + mobileFooter.height > 844 || !mobileHeading || mobileHeading.y < 0) throw new Error('Mobile form header or save controls are outside the viewport.');
  await page.getByLabel('Patient registration', { exact: true }).selectOption('DEMO-002');
  await page.getByLabel('First name', { exact: true }).fill('Sam');
  await page.getByLabel('Last name', { exact: true }).fill('Taylor');
  await page.getByLabel('Presenting complaint', { exact: true }).fill('Test');
  await page.getByLabel('Assigned priority', { exact: true }).selectOption('3');
  await page.getByRole('dialog').getByRole('button', { name: 'Register patient', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('already has an active visit');
  await page.getByRole('button', { name: 'Close patient details' }).click();
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Browser checks passed: registration, editing, persistence, discharge, resources, activity, filters, display privacy, mobile layout, and duplicate validation.');
} finally {
  await browser.close();
}
